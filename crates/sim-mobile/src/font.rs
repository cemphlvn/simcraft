//! Text as shapes: a 5×7 pixel font, each lit pixel a small rounded box, drawn by the same pipeline as everything
//! else (no font files, no texture atlas). Enough for labels and numbers in the playground and HUDs; a real font
//! comes when a game needs one. Lower case is drawn as upper case; unknown characters as a space.

use crate::gesture::Px;
use crate::layer::{Color, Frame, Layer, Rect, Shape};

/// The glyph of `c`: 7 rows of 5 bits, the leftmost pixel in bit 4.
fn glyph(c: char) -> [u8; 7] {
    match c.to_ascii_uppercase() {
        'A' => [0x0e, 0x11, 0x11, 0x1f, 0x11, 0x11, 0x11],
        'B' => [0x1e, 0x11, 0x11, 0x1e, 0x11, 0x11, 0x1e],
        'C' => [0x0e, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0e],
        'D' => [0x1e, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1e],
        'E' => [0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x1f],
        'F' => [0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x10],
        'G' => [0x0e, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0f],
        'H' => [0x11, 0x11, 0x11, 0x1f, 0x11, 0x11, 0x11],
        'I' => [0x0e, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0e],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0c],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1f],
        'M' => [0x11, 0x1b, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0e, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e],
        'P' => [0x1e, 0x11, 0x11, 0x1e, 0x10, 0x10, 0x10],
        'Q' => [0x0e, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0d],
        'R' => [0x1e, 0x11, 0x11, 0x1e, 0x14, 0x12, 0x11],
        'S' => [0x0f, 0x10, 0x10, 0x0e, 0x01, 0x01, 0x1e],
        'T' => [0x1f, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0a, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0a],
        'X' => [0x11, 0x11, 0x0a, 0x04, 0x0a, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x11, 0x0a, 0x04, 0x04, 0x04],
        'Z' => [0x1f, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1f],
        '0' => [0x0e, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0e],
        '1' => [0x04, 0x0c, 0x04, 0x04, 0x04, 0x04, 0x0e],
        '2' => [0x0e, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1f],
        '3' => [0x1f, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0e],
        '4' => [0x02, 0x06, 0x0a, 0x12, 0x1f, 0x02, 0x02],
        '5' => [0x1f, 0x10, 0x1e, 0x01, 0x01, 0x11, 0x0e],
        '6' => [0x06, 0x08, 0x10, 0x1e, 0x11, 0x11, 0x0e],
        '7' => [0x1f, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0e, 0x11, 0x11, 0x0e, 0x11, 0x11, 0x0e],
        '9' => [0x0e, 0x11, 0x11, 0x0f, 0x01, 0x02, 0x0c],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x0c, 0x0c],
        ':' => [0x00, 0x0c, 0x0c, 0x00, 0x0c, 0x0c, 0x00],
        '-' => [0x00, 0x00, 0x00, 0x1f, 0x00, 0x00, 0x00],
        '+' => [0x00, 0x04, 0x04, 0x1f, 0x04, 0x04, 0x00],
        '/' => [0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10],
        '%' => [0x18, 0x19, 0x02, 0x04, 0x08, 0x13, 0x03],
        _ => [0; 7],
    }
}

/// How wide `text` is at pixel size `px` (a glyph is 5 pixels and a 1-pixel gap).
pub fn width(text: &str, px: f32) -> f32 {
    let n = text.chars().count() as f32;
    if n == 0.0 { 0.0 } else { (n * 6.0 - 1.0) * px }
}

/// Height of a line at pixel size `px`.
pub fn height(px: f32) -> f32 {
    7.0 * px
}

/// Draws `text` with its top left at `at`, each font pixel `px` screen pixels.
pub fn text(frame: &mut Frame, layer: Layer, order: i32, at: Px, px: f32, color: Color, text: &str) {
    for (i, c) in text.chars().enumerate() {
        let x0 = at.x + i as f32 * 6.0 * px;
        for (row, bits) in glyph(c).iter().enumerate() {
            for col in 0..5 {
                if bits >> (4 - col) & 1 == 1 {
                    let rect = Rect::new(x0 + col as f32 * px, at.y + row as f32 * px, px * 0.92, px * 0.92);
                    frame.push(layer, order, Shape::Box { rect, r: px * 0.25, color });
                }
            }
        }
    }
}

/// Draws `text` centred on `center`.
pub fn centered(frame: &mut Frame, layer: Layer, order: i32, center: Px, px: f32, color: Color, s: &str) {
    let at = Px::new(center.x - width(s, px) / 2.0, center.y - height(px) / 2.0);
    text(frame, layer, order, at, px, color, s);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_label_character_has_a_glyph() {
        for c in "ROPE TOUCH FEEL TILT FPS 0123456789 .:-+/%".chars().filter(|&c| c != ' ') {
            assert_ne!(glyph(c), [0; 7], "no glyph for {c:?}");
        }
        assert_eq!(glyph('a'), glyph('A'));
    }

    #[test]
    fn text_is_lit_pixels_and_measures_right() {
        let mut f = Frame::default();
        text(&mut f, Layer::Hud, 0, Px::new(0.0, 0.0), 2.0, Color::hex(0xffffff), "I");
        // An I: 3 + 1 + 1 + 1 + 1 + 1 + 3 lit pixels.
        assert_eq!(f.sorted().len(), 11);
        assert_eq!(width("AB", 2.0), 22.0);
        assert_eq!(width("", 2.0), 0.0);
    }
}
